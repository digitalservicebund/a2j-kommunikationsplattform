import { sortBy } from "es-toolkit";
import z from "zod";
import {
  VerfahrenResponseApiSchema,
  VerfahrenStatusApiSchema,
} from "../../infrastructure/schemas/verfahren.schema";
import { BeteiligungSchema } from "../beteiligung/beteiligung.entity";
import {
  ROLLENBEZEICHNUNG_CODE_BEKLAGTE,
  ROLLENBEZEICHNUNG_CODE_KLAEGERIN,
  ROLLENBEZEICHNUNG_CODE_PROZESSBEVOLLMAECHTIGTE,
} from "../codelisten/rollenbezeichnung.entity";

/**
 * Schema for {@link VerfahrenStatus}.
 */
export const VerfahrenStatusSchema = VerfahrenStatusApiSchema;

/**
 * Signals where a Verfahren is in its lifecycle.
 *
 * - "ERSTELLT": The Verfahren was just created, but not yet submitted to the
 *   court (*eingereicht*) yet. This is essentially a draft state in which
 *   most Verfahren details can be freely edited.
 *
 * - "BEANTRAGT": A submission has been requested. Editing is disabled.
 *
 * - "FEHLGESCHLAGEN": Submitting the Verfahren failed. The Verfahren details
 *   become editable again, just like in the "ERSTELLT" state.
 *
 * - "EINGEREICHT": The Verfahren was successfully submitted and sending of
 *   the uploaded Dokumente (e.g., the *Klageschrift*), as well as the XJustiz
 *   message with the Verfahren details, is underway.
 *
 * - "VERSENDET": All Dokumente have been successfully to the court.
 *
 * - "VERAKTET": The Verfahren has been created in the court's Fachverfahren
 *   system, at which point it receives an official Aktenzeichen.
 *
 * - "GELÖSCHT": The Verfahren has been deleted. This is a temporary state
 *   until the Verfahren has been removed from the system completely.
 */
export type VerfahrenStatus = z.infer<typeof VerfahrenStatusSchema>;

/**
 * Schema for {@link Verfahren}.
 */
export const VerfahrenSchema = VerfahrenResponseApiSchema.transform(
  (verfahrenFromApi) => ({
    id: verfahrenFromApi.id,
    aktenzeichenGericht: verfahrenFromApi.aktenzeichen_gericht,
    verfahrensgegenstand: verfahrenFromApi.verfahrensgegenstand,
    kurzrubrum: verfahrenFromApi.kurzrubrum,
    status: verfahrenFromApi.status,
    statusGeaendertAm: verfahrenFromApi.status_geaendert_am,
    erstelltVon: verfahrenFromApi.erstellt_von,
    erstelltAm: verfahrenFromApi.erstellt_am,
    eingereichtAm: verfahrenFromApi.eingereicht_am,
    gericht: verfahrenFromApi.gericht,

    // As of November 2026, the KomPla API does not preserve the order of
    // the `beteiligungen` array sent to `PUT /api/v1/verfahren/{id}`; a
    // subsequent `GET /api/v1/verfahren/{id}` is likely to see a different
    // order. This is a problem because written communication commonly uses
    // order-dependent shorthands like "Kläger 2" which require a stable
    // ordering.
    //
    // To work around this, sort the Beteiligungen representing Parteien and
    // Vertretungen by their Rollennummer. This ensures at least a stable
    // ordering among those Beteiligte, making "Kläger 2" etc. well-defined.
    // In case of Beteiligungen generated by this frontend, which use the
    // Rollennummer scheme `${paddedIndex}:${rollenbezeichnungCode}`, this
    // even restores the order in which the user entered the Beteiligte in
    // the first place.
    //
    // TODO: Stop sorting once the API preserves Beteiligung order.
    beteiligungen: sortBy(
      verfahrenFromApi.beteiligungen.map((beteiligung) =>
        BeteiligungSchema.parse(beteiligung),
      ),
      [
        (beteiligung) =>
          beteiligung.rollen.find(
            (rolle) =>
              rolle.rollenbezeichnung.code ===
                ROLLENBEZEICHNUNG_CODE_KLAEGERIN ||
              rolle.rollenbezeichnung.code ===
                ROLLENBEZEICHNUNG_CODE_BEKLAGTE ||
              rolle.rollenbezeichnung.code ===
                ROLLENBEZEICHNUNG_CODE_PROZESSBEVOLLMAECHTIGTE,
          )?.rollennummer ?? "ZZZ",
        "id",
      ],
    ),
  }),
);

/**
 * Represents the proceedings of a particular court case.
 *
 * This is the central domain entity of the KomPla. It holds details about a
 * court case - such as its participants (Beteiligungen) - and acts as
 * container for all communication between the Verfahren's parties and the
 * court (Einreichungen, Dokumente).
 */
export type Verfahren = z.infer<typeof VerfahrenSchema>;

/**
 * Verfahrensgegenstand every new Verfahren starts with; the user can change
 * it once the Verfahren has been created.
 */
export const DEFAULT_VERFAHRENSGEGENSTAND = "Zahlungsklage";
